"""What each indexer needs before and while it runs, and the least trust that lets it run.

Every plan fetches dependencies in a step that executes nothing of the repository, then runs the indexer with
as little of the repository's own code as the indexer allows:

- Python, TypeScript: no `pip` call, no lifecycle scripts.
- Rust: `cargo fetch --locked` (checksummed by Cargo.lock), then rust-analyzer offline with its build-script
  command replaced by `true` and proc macros off, so no `build.rs` or proc macro of the repository or its
  dependencies runs; `.cargo/` and `rust-toolchain*` of the repository are dropped. Code generated by build
  scripts or macros is missing from the index, which the completeness record shows.
- Go: `go mod download` (checksummed by go.sum), then scip-go offline with cgo off and the local toolchain.
- Kotlin: scip-java can only index through the repository's Gradle build, which executes its build scripts,
  plugins and downloaded code. That runs in place only when ORACLE_SANDBOX=1 vouches for an isolated, secret-free,
  throwaway runner; otherwise in a throwaway container with nothing of the host mounted but the snapshot and the
  caches; without either the repository is skipped and counted, never scored as empty.

What an indexer needs beside the sources goes into the exported tree, a throwaway copy of the pinned commit; the
mirror and the work checkout the engine reads are never written to, and no measured project is edited.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

import corpus as corpus_config
from toolbin import tool_path

CACHE = corpus_config.CACHE
TOOLS = corpus_config.ROOT / "tools"
SANDBOX_VARIABLE = "ORACLE_SANDBOX"
NEEDS_SANDBOX = "needs_sandbox"


@dataclass
class Plan:
    command: list[str] | None
    env: dict[str, str]
    blocked: str = ""
    runs_third_party_code: bool = False  # the command, run on this machine, executes build tooling or scripts of the repository


CONTAINER_MARKERS = ("docker", "containerd", "kubepods", "lxc", "podman")


POD_MOUNT = Path("/var/run/secrets/kubernetes.io/serviceaccount")


def in_container(
    dockerenv: Path = Path("/.dockerenv"),
    cgroup: Path = Path("/proc/self/cgroup"),
    pod_mount: Path = POD_MOUNT,
) -> bool:
    """This process runs inside a container: Docker's marker file, the service-account volume the kubelet mounts into a pod
    (a pod under a cgroup namespace shows `0::/` and no marker file; a mounted fact, not a variable anyone can set), or a
    container runtime in its cgroup path."""
    if dockerenv.exists() or pod_mount.is_dir():
        return True
    try:
        return any(marker in cgroup.read_text(encoding="utf-8", errors="replace") for marker in CONTAINER_MARKERS)
    except OSError:
        return False


def sandboxed() -> bool:
    """ORACLE_SANDBOX=1 is a claim about the machine, believed only where a container is detected."""
    return os.environ.get(SANDBOX_VARIABLE) == "1" and in_container()


def refuse_unfounded_sandbox_claim() -> None:
    """Exit when ORACLE_SANDBOX=1 is set where no container is detected: the variable alone vouches for nothing."""
    if os.environ.get(SANDBOX_VARIABLE) == "1" and not in_container():
        raise SystemExit(f"{SANDBOX_VARIABLE}=1 refused: no container is detected (/.dockerenv or the cgroup); unset it")


def _succeeds(command: list[str], cwd: Path, env: dict[str, str], timeout: int) -> bool:
    try:
        return subprocess.run(command, cwd=cwd, env=env, capture_output=True, timeout=timeout, check=False).returncode == 0
    except subprocess.TimeoutExpired:
        return False


def plan_python(ctx: Context) -> Plan:
    # A repository's own `[tool.pyright] include` narrows what scip-python reads (click's old pins keep 24 of 70 files);
    # a pyrightconfig.json outranks it, so the oracle indexes every file.
    (ctx.tree / "pyrightconfig.json").write_text(json.dumps({"include": ["."]}), encoding="utf-8")
    environment = ctx.home / "environment.json"
    environment.write_text("[]", encoding="utf-8")  # no pip call: nothing of the repository's environment runs
    command = [
        str(TOOLS / "node_modules" / ".bin" / "scip-python"),
        "index",
        ".",
        f"--project-name={ctx.repo.name}",
        f"--project-version={ctx.sha}",
        f"--output={ctx.out}",
        f"--environment={environment}",
        "--quiet",
    ]
    return Plan(command, ctx.env)


COVERING_OPTIONS = {"allowJs": True, "noEmit": True, "skipLibCheck": True}
RESOLUTION_OPTIONS = {"module": "esnext", "moduleResolution": "bundler"}
REPO_CONFIG = "tsconfig.repo.json"


def _read_config(config: Path) -> dict:
    """The tsconfig as JSON; comments on their own lines are tolerated, anything else unreadable is empty."""
    try:
        return json.loads(re.sub(r"^\s*//.*$", "", config.read_text(encoding="utf-8"), flags=re.MULTILINE))
    except (OSError, ValueError):
        return {}


def _is_solution_style(data: dict) -> bool:
    """A tsconfig that only lists `references` compiles no file itself: scip-typescript then reads just the projects it names."""
    return data.get("files") == [] and "include" not in data and bool(data.get("references"))


def cover_everything(tree: Path) -> None:
    """Index every script file: put a root tsconfig over the repository's that includes them all.

    The repository's own `include`, `exclude` and `references` decide what scip-typescript reads, and they leave
    out benchmarks, workspace packages and configs (hono: a third of its files). `--infer-tsconfig` does not help:
    it picks the JavaScript-aware config only when no `.ts` file turns up in its first thousand paths, and the
    installed `node_modules` always holds `.d.ts` files, so a JavaScript repository was indexed with a config
    that ignores JavaScript (express: "no files got indexed"). The oracle's config extends the repository's, so
    module resolution, `paths` and `jsx` stay, and the repository's file is kept as tsconfig.repo.json.
    """
    config = tree / "tsconfig.json"
    options = dict(COVERING_OPTIONS)
    body: dict = {"oracleCovering": True, "include": ["**/*"], "exclude": ["**/node_modules"]}
    if config.exists():
        existing = _read_config(config)
        if existing.get("oracleCovering"):
            return
        config.rename(tree / REPO_CONFIG)
        if _is_solution_style(existing):
            options.update(RESOLUTION_OPTIONS)
        else:
            body["extends"] = f"./{REPO_CONFIG}"
    else:
        options.update(RESOLUTION_OPTIONS)
    body["compilerOptions"] = options
    config.write_text(json.dumps(body), encoding="utf-8")


def plan_typescript(ctx: Context) -> Plan:
    if ctx.install and (ctx.tree / "package.json").exists():
        flags = ["--ignore-scripts", "--no-audit", "--no-fund", "--no-package-lock"]
        _succeeds(["npm", "install", *flags], ctx.tree, ctx.env, ctx.timeout)
    cover_everything(ctx.tree)
    return Plan([str(TOOLS / "node_modules" / ".bin" / "scip-typescript"), "index", f"--output={ctx.out}"], ctx.env)


def _tail(command: list[str], cwd: Path, env: dict[str, str], timeout: int) -> str | None:
    """None when the command succeeds, else the end of what it said: the cause, not just that it failed."""
    try:
        done = subprocess.run(command, cwd=cwd, env=env, capture_output=True, timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return "timeout"
    if done.returncode == 0:
        return None
    return (done.stderr + done.stdout).decode(errors="replace")[-400:].strip().replace("\n", " | ")


def plan_rust(ctx: Context) -> Plan:
    shutil.rmtree(ctx.tree / ".cargo", ignore_errors=True)
    for stray in ctx.tree.glob("rust-toolchain*"):
        stray.unlink()
    rustup = os.environ.get("RUSTUP_HOME") or str(Path.home() / ".rustup")
    env = {**ctx.env, "CARGO_HOME": str(CACHE / "cargo-home"), "RUSTUP_HOME": rustup}
    if "RUSTUP_TOOLCHAIN" in os.environ:
        env["RUSTUP_TOOLCHAIN"] = os.environ["RUSTUP_TOOLCHAIN"]
    failure = _tail(["cargo", "fetch", "--locked"], ctx.tree, env, ctx.timeout)
    if failure:
        return Plan(None, env, f"dependency fetch failed: cargo fetch --locked: {failure}")
    config = ctx.home / "rust-analyzer.json"
    config.write_text(
        json.dumps({"cargo": {"buildScripts": {"overrideCommand": ["true"]}}, "procMacro": {"enable": False}}), encoding="utf-8"
    )
    analyzer = tool_path(ctx.corpus.tools["rust-analyzer"])
    command = [str(analyzer), "scip", ".", "--output", str(ctx.out), "--config-path", str(config), "--exclude-vendored-libraries"]
    return Plan(command, {**env, "CARGO_NET_OFFLINE": "true"})


# The JDK a laptop runs Gradle in (a throwaway container), pinned by digest: eclipse-temurin:21-jdk of 2026-11-05.
SANDBOX_IMAGE = (
    "eclipse-temurin@sha256:ebfbb18d11ff163ee83b21258acf12248af48d22a0fdfdc68fa1a1516c05976a"  # pragma: allowlist secret
)
# The JDK with Maven 3.9 for a Maven project, pinned by digest: maven:3.9-eclipse-temurin-21 of 2026-09-26.
MAVEN_IMAGE = "maven@sha256:99e61abcff91a9b1333463bd8451fb18495d6eba9250ac66a338b518f8278320"  # pragma: allowlist secret
GRADLE_OPTS = "-Dorg.gradle.daemon=false -Xmx4g"


GRADLE_VERSIONS_BUDGET = 1 << 30  # bytes the per-version Gradle files may take before they are dropped


def _tree_size(path: Path) -> int:
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file() and not f.is_symlink())


def trim_gradle_home(home: Path, budget: int = GRADLE_VERSIONS_BUDGET) -> None:
    """Drop the distributions and per-version caches of Gradle once they pass `budget`.

    Each snapshot's wrapper names its own Gradle, a long history names a dozen, and each takes a few hundred
    megabytes; they are fetched again on demand. The dependency cache and the toolchains stay.
    """
    versions = [*home.glob("wrapper/dists/gradle-*"), *home.glob("caches/[0-9]*")]
    if sum(_tree_size(path) for path in versions) > budget:
        for path in versions:
            shutil.rmtree(path, ignore_errors=True)


def plan_kotlin(ctx: Context) -> Plan:
    return _plan_jvm(ctx, "gradle")


def plan_java(ctx: Context) -> Plan:
    """Maven when the repository is a Maven project, Gradle otherwise: both run third-party build code."""
    gradle = any(
        (ctx.tree / name).exists() for name in ("build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts")
    )
    return _plan_jvm(ctx, "maven" if (ctx.tree / "pom.xml").exists() and not gradle else "gradle")


def _plan_jvm(ctx: Context, build_tool: str) -> Plan:
    """scip-java indexes through the repository's build, which runs third-party code.

    Inside a container that is detected (ORACLE_SANDBOX=1 and /.dockerenv or the cgroup) it runs in place. Anywhere
    else it runs in a throwaway container started from here: only the snapshot, the launcher, the output directory and
    the Gradle cache are mounted, no host home, no credentials, no environment. Without Docker the repository is
    skipped and counted, never scored as empty: Gradle never runs on the host.
    """
    launcher = tool_path(ctx.corpus.tools["scip-java"])
    start = ["java", "-jar", str(launcher)] if launcher.read_bytes()[:2] == b"PK" else [str(launcher)]
    gradle = CACHE / "gradle-home"
    maven = CACHE / "maven-home"
    trim_gradle_home(gradle)
    if sandboxed():
        env = {**ctx.env, "GRADLE_USER_HOME": str(gradle), "GRADLE_OPTS": GRADLE_OPTS}
        if "JAVA_HOME" in os.environ:
            env["JAVA_HOME"] = os.environ["JAVA_HOME"]
        return Plan([*start, "index", f"--build-tool={build_tool}", "--output", str(ctx.out)], env, runs_third_party_code=True)
    docker = shutil.which("docker")
    if docker is None:
        return Plan(
            None,
            ctx.env,
            f"{NEEDS_SANDBOX}: {build_tool} runs the repository's build; it runs in a container, and none can be started",
        )
    gradle.mkdir(parents=True, exist_ok=True)
    maven.mkdir(parents=True, exist_ok=True)
    command = [
        docker, "run", "--rm", "--cpus", "4", "--memory", "8g",
        "-v", f"{ctx.tree}:/work",
        "-v", f"{launcher}:/scip-java.jar:ro",
        "-v", f"{ctx.out.parent}:/out",
        "-v", f"{gradle}:/gradle-home",
        "-v", f"{maven}:/root/.m2",
        "-e", "GRADLE_USER_HOME=/gradle-home",
        "-e", f"GRADLE_OPTS={GRADLE_OPTS}",
        "-w", "/work",
        MAVEN_IMAGE if build_tool == "maven" else SANDBOX_IMAGE,
        "java", "-jar", "/scip-java.jar", "index", f"--build-tool={build_tool}", "--output", f"/out/{ctx.out.name}",
    ]  # fmt: skip
    # The client needs its own configuration to find the daemon; nothing of it reaches the container.
    client = {k: v for k, v in os.environ.items() if k in {"PATH", "HOME", "DOCKER_HOST", "DOCKER_CONTEXT"}}
    return Plan(command, client)


def clean_gradle_outputs(tree: Path) -> None:
    """Drop what a Gradle run left in the snapshot (`.gradle/`, each module's `build/`): the sources are what stay."""
    shutil.rmtree(tree / ".gradle", ignore_errors=True)
    for build in tree.rglob("build"):
        if build.is_dir() and any((build.parent / name).exists() for name in ("build.gradle", "build.gradle.kts")):
            shutil.rmtree(build, ignore_errors=True)


@dataclass
class Context:
    corpus: corpus_config.Corpus
    repo: corpus_config.Repo
    sha: str
    tree: Path
    out: Path
    home: Path
    env: dict[str, str]
    install: bool
    timeout: int


def plan_go(ctx: Context) -> Plan:
    """`go mod download` (checksummed by go.sum) runs none of the repository's code; scip-go then loads the packages
    offline with cgo off, so no generator, no cgo build and no test runs."""
    go = CACHE / "go"
    env = {
        **ctx.env,
        "GOMODCACHE": str(go / "mod"),
        "GOCACHE": str(go / "build"),
        "GOPATH": str(go / "path"),
        "GOTOOLCHAIN": "local",
        "GOWORK": "off",
        "GOFLAGS": "-mod=readonly",
        "CGO_ENABLED": "0",
        "GOPROXY": "https://proxy.golang.org",
    }
    failure = _tail(["go", "mod", "download"], ctx.tree, env, ctx.timeout)
    if failure and "no modules specified" in failure:
        failure = None  # a module with no requirement has nothing to download, which newer Go reports as an error
    if failure:
        return Plan(None, env, f"dependency fetch failed: go mod download: {failure}")
    scip_go = tool_path(ctx.corpus.tools["scip-go"])
    command = [
        str(scip_go),
        "index",
        "--output",
        str(ctx.out),
        "--module-version",
        ctx.sha,
        "--repository-remote",
        f"example.invalid/{ctx.repo.name}",
        "--quiet",
    ]
    return Plan(command, {**env, "GOPROXY": "off"})


