"""The state of each (language, relation) cell: what the engine declares, checked against the measurement.

The engine declares each cell `precise`, `heuristic` or `none` (T16) in a facts file (`diffctx.cell-facts.v2`, documented
in README.md). A declared state is checked, never believed:

- `precise` passes every condition of `gates.toml` `[precise]` in every row of the cell (each mode, each paired run): head
  precision and recall at the floors in every row, no incomplete complete answer (the false complete negative is its
  special case), no false fold, at least the minimum of true relations (per paired run, over its
  modes) and of decoys in the cell, a measured cell that does not fail against the base, a fresh seed for the language, the replaced path deleted;
- `heuristic` answers as candidates: its rows break no safety row (an incomplete complete answer or a false fold is a claim a
  candidate does not make);
- `none` is a named unknown, never a zero: the facts name what is unknown, its numbers are never shown, and it too breaks
  no safety row.

A cell whose declaration is not true reads `untrue` with the reasons; a measured cell no declaration names reads `untrue` as undeclared.
The README's table is generated from the result (`--readme`), and `report.py --cell-facts` prints the same verdict.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import NamedTuple

from gates import Threshold, holds, load_gates
from tables import budget_label, table

FACTS_SCHEMA = "diffctx.cell-facts.v2"
STATES = ("precise", "heuristic", "none")
UNTRUE = "untrue"
README = Path(__file__).with_name("README.md")
BEGIN = "<!-- cell-states:begin (generated by cellstate.py --readme; edit gates.toml or the measurement, not this table) -->"
END = "<!-- cell-states:end -->"
README_HEADING = "## Cell states"
COLUMNS = ["Language", "Relation", "Declared", "State", "Commits", "Sites", "Head P", "Head R", "Notes"]
INCOMPLETE_GATE = "safety.incomplete_complete"  # the false complete negative is its special case, no row of its own
SAFETY_GATES = (INCOMPLETE_GATE, "safety.false_fold")
DECLARED_GATE = "declared.every_state_true"
Observation = tuple[str, object, str]  # source, value, what the number is made of


@dataclass(frozen=True)
class CellFacts:
    """What the engine says of one cell: its state and the witness that backs the claims a measurement cannot see."""

    declared: str
    old_path_deleted: str | None = None  # the commit that deleted the path the resolver replaced
    unknown: str | None = None  # what a `none` cell does not know
    decoys: int | None = None  # the decoys its corpus cases hold


@dataclass(frozen=True)
class Facts:
    """The engine at the head: per language its fresh seed, per (language, relation) its declaration.

    Each claim carries its witness (the seed's name, the commit that deleted the path), so none is a bare yes.
    """

    fresh_seed: dict[str, str]
    cells: dict[tuple[str, str], CellFacts]


@dataclass(frozen=True)
class CellState:
    language: str
    relation: str
    declared: str | None  # the engine's state, None where the facts name no state for a measured cell
    state: str  # the declared state when it is true, else `untrue`
    reasons: tuple[str, ...]  # what keeps the cell from `precise`; for `none`, what is unknown
    violations: tuple[str, ...]  # why the declared state is not true
    commits: int | None  # of the weakest row; so are the next three. None for a `none` cell: never a zero
    sites: int | None
    head_precision: float | None
    head_recall: float | None
    values: dict  # the weakest value of each `precise.*` gate over the cell, a bool for a required one
    failed: tuple[str, ...]  # the gates the cell misses


def _witness(value: object, where: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{where} must be a non-empty witness string")
    return value


def _fresh_seeds(value: object) -> dict[str, str]:
    if not isinstance(value, dict):
        raise ValueError("fresh_seed must map a language to its witness")
    return {language: _witness(witness, f"fresh_seed {language!r}") for language, witness in value.items()}


def _cell_facts(key: str, data: object) -> tuple[tuple[str, str], CellFacts]:
    language, _, relation = key.partition("/")
    if not language or not relation:
        raise ValueError(f"cells key {key!r} must be 'language/relation'")
    if not isinstance(data, dict) or data.get("state") not in STATES:
        raise ValueError(f"cells {key!r} must be an object whose state is one of {', '.join(STATES)}")
    state = data["state"]
    deleted = data.get("old_path_deleted")
    decoys = data.get("decoys")
    if decoys is not None and (isinstance(decoys, bool) or not isinstance(decoys, int) or decoys < 0):
        raise ValueError(f"cells {key!r}: decoys must be a count")
    unknown = _witness(data.get("unknown"), f"cells {key!r}: a none cell's unknown") if state == "none" else None
    return (language, relation), CellFacts(
        state, _witness(deleted, f"cells {key!r}: old_path_deleted") if deleted is not None else None, unknown, decoys
    )


def parse_facts(data: dict) -> Facts:
    if data.get("schema") != FACTS_SCHEMA:
        raise ValueError(f"facts file: schema must be {FACTS_SCHEMA!r}, got {data.get('schema')!r}")
    cells = data.get("cells", {})
    if not isinstance(cells, dict):
        raise ValueError("cells must map 'language/relation' to its declaration")
    return Facts(_fresh_seeds(data.get("fresh_seed", {})), dict(_cell_facts(key, found) for key, found in cells.items()))


def load_facts(path: Path) -> Facts:
    return parse_facts(json.loads(path.read_text(encoding="utf-8")))


class Miss(NamedTuple):
    gate: str
    text: str
    uncounted: bool = False  # the run carries no count for the row: unknown, not a broken row


def _row_misses(row: dict, where: str, gates: dict[str, Threshold]) -> list[Miss]:
    """What this one row of a cell misses; `where` says which mode of which paired run."""
    misses: list[Miss] = []
    if "precise.measured_cell" in gates and row["state"] == "unmeasured":
        misses.append(Miss("precise.measured_cell", f"unmeasured at {where}"))
    if row["failing"]:
        misses.append(Miss("precise.measured_cell", f"{', '.join(row['failing'])} fail against the base at {where}"))
    for name in ("precision", "recall"):
        gate = f"precise.{name}"
        head = row[name]["head"]
        if head is None:
            misses.append(Miss(gate, f"{name} has no truth at {where}"))
        elif not holds(gates[gate], head):
            misses.append(Miss(gate, f"{name} {head} under {gates[gate].limit} at {where}"))
    for field, gate, text in (
        ("false_fold_head", "safety.false_fold", "false folds"),
        ("incomplete_complete_head", INCOMPLETE_GATE, "incomplete complete answers"),
    ):
        limit = gates[gate].limit
        if row[field] is None:
            misses.append(Miss(gate, f"{text} not counted at {where}", uncounted=True))
        elif row[field] > limit:
            misses.append(Miss(gate, f"{row[field]} {text} at {where}, limit {limit}"))
    return misses


def _true_relations(found: list[tuple[dict, str, str]]) -> int | None:
    """The true relations the cell is measured on: per paired run the sites of all its modes, the thinnest run's."""
    per_run: dict[str, int] = {}
    for row, _, run in found:
        per_run[run] = per_run.get(run, 0) + row["truth"]
    return min(per_run.values(), default=None)


def _weakest(found: list[tuple[dict, str, str]], pick: Callable[[dict], float | None]) -> float | None:
    return min((v for row, _, _ in found if (v := pick(row)) is not None), default=None)


def _engine_misses(language: str, declared: CellFacts | None, facts: Facts, gates: dict[str, Threshold]) -> list[Miss]:
    """What the engine's own facts cannot back: a fresh seed, the deleted path, the decoys."""
    misses: list[Miss] = []
    if "precise.fresh_seed" in gates and language not in facts.fresh_seed:
        misses.append(Miss("precise.fresh_seed", "no fresh seed for the language"))
    if "precise.old_path_deleted" in gates and not (declared and declared.old_path_deleted):
        misses.append(Miss("precise.old_path_deleted", "old path not deleted"))
    if "precise.decoys" in gates:
        decoys = declared.decoys if declared else None
        if decoys is None:
            misses.append(Miss("precise.decoys", "no decoy count in the facts"))
        elif not holds(gates["precise.decoys"], decoys):
            misses.append(Miss("precise.decoys", f"{decoys} decoys, under {gates['precise.decoys'].limit}"))
    return misses


def _violations(declared: CellFacts | None, misses: list[Miss]) -> list[str]:
    """Why the declared state is not true. Precise claims every gate; the other two claim no incomplete complete answer
    or fold."""
    if declared is None:
        return ["undeclared: the engine's facts name no state for this measured cell"]
    if declared.declared == "precise":
        return [miss.text for miss in misses]
    return [miss.text for miss in misses if miss.gate in SAFETY_GATES and not miss.uncounted]


def _cell(key: tuple[str, str], found: list[tuple[dict, str, str]], facts: Facts, gates: dict[str, Threshold]) -> CellState:
    language, relation = key
    declared = facts.cells.get(key)
    misses = [miss for row, where, _ in found for miss in _row_misses(row, where, gates)]
    if not found:
        misses.append(Miss("precise.measured_cell", "no measured row"))
    relations = _true_relations(found)
    if relations is not None and "precise.true_relations" in gates and not holds(gates["precise.true_relations"], relations):
        misses.append(
            Miss("precise.true_relations", f"{relations} true relations, under {gates['precise.true_relations'].limit}")
        )
    engine = _engine_misses(language, declared, facts, gates)
    misses += engine
    violations = _violations(declared, misses)
    state = UNTRUE if violations else declared.declared if declared else UNTRUE
    unknown = declared is not None and declared.declared == "none"
    failed = {miss.gate for miss in misses}
    values = {
        "precise.precision": _weakest(found, lambda r: r["precision"]["head"]),
        "precise.recall": _weakest(found, lambda r: r["recall"]["head"]),
        "precise.true_relations": relations,
        "precise.decoys": declared.decoys if declared else None,
        **{gate: gate not in failed for gate in ("precise.measured_cell", "precise.fresh_seed", "precise.old_path_deleted")},
    }
    reasons = (f"unknown: {declared.unknown}",) if unknown and declared else tuple(miss.text for miss in misses)
    shown = None if unknown else found
    return CellState(
        language,
        relation,
        declared.declared if declared else None,
        state,
        reasons,
        tuple(violations),
        None if shown is None else _weakest(shown, lambda r: r["commits"]),
        None if shown is None else _weakest(shown, lambda r: r["truth"]),
        None if shown is None else _weakest(shown, lambda r: r["precision"]["head"]),
        None if shown is None else _weakest(shown, lambda r: r["recall"]["head"]),
        values,
        tuple(sorted(failed)),
    )


def classify(paired_entries: list[dict], facts: Facts, gates: dict[str, Threshold]) -> list[CellState]:
    """Every cell of the paired tables and of the facts, by (language, relation)."""
    rows: dict[tuple[str, str], list[tuple[dict, str, str]]] = {key: [] for key in facts.cells}
    for entry in paired_entries:
        run = f"{entry['head']}, budget {budget_label(entry['budgets'][1])}"
        for row in entry["result"]["rows"]:
            rows.setdefault((row["language"], row["relation"]), []).append((row, f"{row['mode']} ({run})", run))
    return [_cell(key, found, facts, gates) for key, found in sorted(rows.items())]


def observations(cells: list[CellState], gates: dict[str, Threshold]) -> dict[str, list[Observation]]:
    """The verdict's `precise.*` lines and the every-state-true line, from the same cells the table shows.

    A `precise.*` gate is judged over the cells declared precise: a required one is true when none of them misses it, a
    floor reads the weakest value among them. With no cell declared precise there is nothing to judge: no line.
    """
    seen: dict[str, list[Observation]] = {}
    precise = [c for c in cells if c.declared == "precise"]
    for gate in (g for g in gates.values() if g.gate.startswith("precise.") and precise):
        failing = [f"{c.language}/{c.relation}" for c in precise if gate.gate in c.failed]
        value: object
        if gate.op == "require":
            value = not failing
        else:
            value = min((v for c in precise if (v := c.values.get(gate.gate)) is not None), default=None)
        detail = f"{len(precise)} cells declared precise" + (f"; failing: {', '.join(failing)}" if failing else "")
        seen[gate.gate] = [("cell facts", value, detail)]
    if DECLARED_GATE in gates and cells:
        untrue = [f"{c.language}/{c.relation}" for c in cells if c.state == UNTRUE]
        detail = f"{len(cells)} cells" + (f"; untrue: {', '.join(untrue)}" if untrue else "")
        seen[DECLARED_GATE] = [("cell facts", not untrue, detail)]
    return seen


def render_table(cells: list[CellState]) -> str:
    rows = [
        [
            c.language,
            c.relation,
            c.declared,
            c.state,
            c.commits,
            c.sites,
            c.head_precision,
            c.head_recall,
            "; ".join(c.violations or c.reasons),
        ]
        for c in cells
    ]
    return table(COLUMNS, rows)


def render_section(cells: list[CellState], gates: dict[str, Threshold]) -> str:
    floors = ", ".join(
        f"{name} {gates[f'precise.{name}'].limit}" for name in ("precision", "recall") if f"precise.{name}" in gates
    )
    minimum = (
        f", at least {gates['precise.true_relations'].limit} true relations per run and "
        f"{gates['precise.decoys'].limit} decoys"
        if "precise.true_relations" in gates and "precise.decoys" in gates
        else ""
    )
    intro = (
        "The engine declares each cell `precise`, `heuristic` or `none`, and a declaration is checked against the "
        f"measurement. A `precise` cell holds head {floors} in every mode and run{minimum}, clean safety rows, a measured cell "
        "that does not fail against the base, a fresh seed and its old path deleted; a `heuristic` cell breaks no "
        "safety row; a `none` cell is a named unknown whose numbers are never shown. A declaration the measurement "
        "refutes reads `untrue`. Commits, sites and the head's numbers are those of the cell's weakest row."
    )
    return "\n".join([README_HEADING, "", intro, "", BEGIN, render_table(cells), END]) + "\n"


def splice(readme: str, section: str) -> str:
    """The README with its generated table replaced; a README without the markers gets the section appended."""
    if BEGIN in readme and END in readme:
        head, _, rest = readme.partition(BEGIN)
        _, _, tail = rest.partition(END)
        body = section.partition(BEGIN)[2].partition(END)[0]
        return f"{head}{BEGIN}{body}{END}{tail}"
    return readme.rstrip("\n") + "\n\n" + section


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="cellstate", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--report", type=Path, required=True, help="report.json of a run built with --against")
    parser.add_argument("--facts", type=Path, required=True, help=f"the engine facts ({FACTS_SCHEMA})")
    parser.add_argument("--gates", type=lambda text: load_gates(Path(text)), metavar="FILE", help="default: gates.toml")
    parser.add_argument("--json", type=Path, help="write the cell states here")
    parser.add_argument("--readme", nargs="?", type=Path, const=README, help="regenerate this README's table (default README.md)")
    options = parser.parse_args(argv)
    gates = load_gates() if options.gates is None else options.gates
    paired_entries = json.loads(options.report.read_text(encoding="utf-8"))["paired"]
    if not paired_entries:
        raise SystemExit(f"{options.report} has no paired run: build it with report.py --against")
    cells = classify(paired_entries, load_facts(options.facts), gates)
    if options.json:
        options.json.write_text(json.dumps([vars(c) for c in cells], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if options.readme:
        options.readme.write_text(
            splice(options.readme.read_text(encoding="utf-8"), render_section(cells, gates)), encoding="utf-8"
        )
    else:
        print(render_table(cells))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
