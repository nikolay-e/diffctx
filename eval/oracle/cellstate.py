"""The state of each (language, relation) cell, derived from the measurement table and never typed in.

A cell is `precise` only when every condition of `gates.toml` `[precise]` holds in every row of it (each mode, each
paired run): the head's precision and recall meet the floors, the safety rows are clean, the cell is measured and does
not fail against the base, the run is a fresh seed for its language, and the path the resolver replaced is deleted.
Any other cell is `heuristic`, with each missing condition named. The two engine facts, a fresh seed and a deleted old
path, are not in a measurement: the orchestrator supplies them from the engine at the head, as a facts file
(`diffctx.cell-facts.v1`, documented in README.md). The README's table is generated from the result (`--readme`).
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import report

FACTS_SCHEMA = "diffctx.cell-facts.v1"
README = Path(__file__).with_name("README.md")
BEGIN = "<!-- cell-states:begin (generated by cellstate.py --readme; edit gates.toml or the measurement, not this table) -->"
END = "<!-- cell-states:end -->"
README_HEADING = "## Cell states"
COLUMNS = ["Language", "Relation", "State", "Commits", "Sites", "Head P", "Head R", "Why not precise"]


@dataclass(frozen=True)
class Facts:
    """What a measurement cannot say: per language its fresh seed, per (language, relation) its deleted old path.

    Each claim carries its witness (the seed's name, the commit that deleted the path), so none is a bare yes.
    """

    fresh_seed: dict[str, str]
    old_path_deleted: dict[tuple[str, str], str]


@dataclass(frozen=True)
class CellState:
    language: str
    relation: str
    state: str
    reasons: tuple[str, ...]
    commits: int | None  # of the weakest row; so are the next three
    sites: int | None
    head_precision: float | None
    head_recall: float | None


def _witnesses(value: object, where: str) -> dict[str, str]:
    if not isinstance(value, dict) or not all(isinstance(k, str) and isinstance(v, str) and v.strip() for k, v in value.items()):
        raise ValueError(f"{where} must map a name to a non-empty witness string")
    return value


def parse_facts(data: dict) -> Facts:
    if data.get("schema") != FACTS_SCHEMA:
        raise ValueError(f"facts file: schema must be {FACTS_SCHEMA!r}, got {data.get('schema')!r}")
    deleted = _witnesses(data.get("old_path_deleted", {}), "old_path_deleted")
    pairs: dict[tuple[str, str], str] = {}
    for key, witness in deleted.items():
        language, _, relation = key.partition("/")
        if not language or not relation:
            raise ValueError(f"old_path_deleted key {key!r} must be 'language/relation'")
        pairs[(language, relation)] = witness
    return Facts(_witnesses(data.get("fresh_seed", {}), "fresh_seed"), pairs)


def load_facts(path: Path) -> Facts:
    return parse_facts(json.loads(path.read_text(encoding="utf-8")))


def _row_reasons(row: dict, where: str, gates: dict[str, report.Threshold]) -> list[str]:
    """What this one row of a cell misses; `where` says which mode of which paired run."""
    reasons = []
    if "precise.measured_cell" in gates and row["state"] == "unmeasured":
        reasons.append(f"unmeasured at {where}")
    if row["failing"]:
        reasons.append(f"{', '.join(row['failing'])} fail against the base at {where}")
    for name in ("precision", "recall"):
        floor = gates[f"precise.{name}"].limit
        head = row[name]["head"]
        if head is None:
            reasons.append(f"{name} has no truth at {where}")
        elif head < floor:
            reasons.append(f"{name} {head} under {floor} at {where}")
    for field, gate, text in (
        ("fcn_head", "safety.false_complete_negatives", "false complete negatives"),
        ("false_fold_head", "safety.false_fold", "false folds"),
    ):
        limit = gates[gate].limit
        if row[field] > limit:
            reasons.append(f"{row[field]} {text} at {where}, limit {limit}")
    return reasons


def _weakest(found: list[tuple[dict, str]], pick: Callable[[dict], float | None]) -> float | None:
    return min((v for row, _ in found if (v := pick(row)) is not None), default=None)


def classify(paired_entries: list[dict], facts: Facts, gates: dict[str, report.Threshold]) -> list[CellState]:
    """Every cell of the paired tables and of the facts, by (language, relation)."""
    rows: dict[tuple[str, str], list[tuple[dict, str]]] = {}
    for entry in paired_entries:
        budget = report.budget_label(entry["budgets"][1])
        for row in entry["result"]["rows"]:
            rows.setdefault((row["language"], row["relation"]), []).append(
                (row, f"{row['mode']} ({entry['head']}, budget {budget})")
            )
    for language, relation in facts.old_path_deleted:
        rows.setdefault((language, relation), [])
    cells = []
    for (language, relation), found in sorted(rows.items()):
        reasons = [reason for row, where in found for reason in _row_reasons(row, where, gates)]
        if not found:
            reasons.append("no measured row")
        if "precise.fresh_seed" in gates and language not in facts.fresh_seed:
            reasons.append("no fresh seed for the language")
        if "precise.old_path_deleted" in gates and (language, relation) not in facts.old_path_deleted:
            reasons.append("old path not deleted")
        cells.append(
            CellState(
                language,
                relation,
                "heuristic" if reasons else "precise",
                tuple(reasons),
                _weakest(found, lambda r: r["commits"]),
                _weakest(found, lambda r: r["truth"]),
                _weakest(found, lambda r: r["precision"]["head"]),
                _weakest(found, lambda r: r["recall"]["head"]),
            )
        )
    return cells


def render_table(cells: list[CellState]) -> str:
    rows = [
        [c.language, c.relation, c.state, c.commits, c.sites, c.head_precision, c.head_recall, "; ".join(c.reasons)]
        for c in cells
    ]
    return report.table(COLUMNS, rows)


def render_section(cells: list[CellState], gates: dict[str, report.Threshold]) -> str:
    precision, recall = gates["precise.precision"].limit, gates["precise.recall"].limit
    intro = (
        f"A cell is `precise` only with head precision of at least {precision} and recall of at least {recall} in every "
        "mode and run, clean safety rows, a measured cell that does not fail against the base, a fresh seed and its old "
        "path deleted; any other cell is `heuristic`. Commits, sites and the head's numbers are those of the cell's "
        "weakest row."
    )
    return "\n".join([README_HEADING, "", intro, "", BEGIN, render_table(cells), END]) + "\n"


def splice(readme: str, section: str) -> str:
    """The README with its generated table replaced; a README without the markers gets the section appended."""
    if BEGIN in readme and END in readme:
        head, _, rest = readme.partition(BEGIN)
        _, _, tail = rest.partition(END)
        table = section.partition(BEGIN)[2].partition(END)[0]
        return f"{head}{BEGIN}{table}{END}{tail}"
    return readme.rstrip("\n") + "\n\n" + section


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="cellstate", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--report", type=Path, required=True, help="report.json of a run built with --against")
    parser.add_argument("--facts", type=Path, required=True, help=f"the engine facts ({FACTS_SCHEMA})")
    parser.add_argument("--gates", type=lambda text: report.load_gates(Path(text)), metavar="FILE", help="default: gates.toml")
    parser.add_argument("--json", type=Path, help="write the cell states here")
    parser.add_argument("--readme", nargs="?", type=Path, const=README, help="regenerate this README's table (default README.md)")
    options = parser.parse_args(argv)
    gates = report.load_gates() if options.gates is None else options.gates
    paired_entries = json.loads(options.report.read_text(encoding="utf-8"))["paired"]
    if not paired_entries:
        raise SystemExit(f"{options.report} has no paired run: build it with report.py --against")
    cells = classify(paired_entries, load_facts(options.facts), gates)
    if options.json:
        options.json.write_text(json.dumps([vars(c) for c in cells], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if options.readme:
        options.readme.write_text(
            splice(options.readme.read_text(encoding="utf-8"), render_section(cells, gates)), encoding="utf-8"
        )
    else:
        print(render_table(cells))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
